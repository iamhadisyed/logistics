	// special getters
	public function getBasketAmount($include_vat = false, $formatted = false)
	{

		$total = 0;

		$BimObj = new Basketitem;
		$where = "basket_id = " . $this->getId();
		$items = $BimObj->getAnyBasketitem($where);

		// calculate vat (to avoid rounding errors, read vat from the basket items)
		$this->vat_total = 0;

		foreach ($items as $item)
		{
			// get parcel group
			$PgpObj = new Parcelgroup($item->getParcelGroupId());

			// for booking parcel groups
			$total += $PgpObj->getTotalPrice() - $PgpObj->getDiscount();

			$this->vat_total += $PgpObj->getVAT();
		}

		if ($include_vat)
		{
			$total += $this->vat_total;
		}

		return ($formatted ? util_money($total) : $total);

	}

	public function getBasketVAT($formatted = false)
	{
		if ($this->vat_total < 0) // If not yet set
		{
			// this forces VAT to be calculate for the basket!!
			$this->getBasketAmount();
		}
		return ($formatted ? util_money($this->vat_total) : $this->vat_total);
	}

	/**
	 * Includes the cost of items in the basket, plus the shipping cost (which is passed in).
	 * Does not include VAT!
	 *
	 * @param bool $formatted
	 */
	public function getBasketTotalAmount($formatted = false)
	{
		$total = 0;
		$total = $this->getBasketAmount(false) + $this->getShippingCost();
		return ($formatted ? util_money($total) : $total);
	}

	public function getBasketTotalAmountPlusVat($formatted = false)
	{
		$total = $this->getBasketTotalAmount(false) + $this->getBasketVAT();
		return ($formatted ? util_money($total) : $total);
	}

