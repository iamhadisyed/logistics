	/**
	 * addToBasket. add a product and size to the basket
	 * @return void
	 */
	public function addToBasket($parcel_group_id, $quantity_to_add = 1)
	{
		// init vars
		$id				= NULL;

		// get parcel group
		$PgpObj 		= new Parcelgroup($parcel_group_id);

		// get the basket id
		$basket_id 		= $this->getId();

		// basket items object
		$BimObj 		= new Basketitem;

		// check to see whether parcel group is already in the basket
		$where			= " basket_id = " . $basket_id . " and parcel_group_id = " . $PgpObj->getId();
		$basket_items 	= $BimObj->getAnyBasketitem($where);
		$basket_item 	= @$basket_items[0];

		// get id
		if (@$basket_item->id > 0 AND $PgpObj->getId() > 0)
		{
			// increment quantity if a product based parcel group
			if ($PgpObj->getProductId() > 0)
			{
				$quantity_to_add = $basket_item->getQuantity() + 1;
			}

			$id = $basket_item->getId();
		}
		else
		{
			$id = 0;
		}

		// create/update basket item
		$BimObj->setId($id);
		$BimObj->setBasketId($basket_id);
		$BimObj->setParcelGroupId($PgpObj->getId());
		$BimObj->setQuantity($quantity_to_add);
		$BimObj->setDiscount(0);
		$BimObj->setActive(1);
		$BimObj->setDeleted("N");
		$BimObj->save();

	}

	/**
	 * getBasket. get the basket contents
	 * @return array
	 */
	public function getBasketItems()
	{
		// If basket is empty get the basket
		if ($this->basketItems == null)
		{
			// get basket items
			$BimObj	 = new Basketitem;
			$where		= " basket_id = " . $this->getId();
			$this->basketItems= $BimObj->getAnyBasketitem($where);
		}
		return $this->basketItems;
	}

