	/**
	 * Generates a transaction code that is guarenteed to be unique.
	 * old - generateTransactionCode
	 *
	 * @return string
	 */
	public function getVendorTransactionCode($renew_flag = false)
	{
		if (($this->vendor_transaction_code == "") || $renew_flag)
		{
			$this->vendor_transaction_code = $this->getId() . "-";
			// get seconds from 1970
			$this->vendor_transaction_code .= time();

			// Update in the database.
			$sql = "UPDATE baskets set vendor_transaction_code='" . $this->vendor_transaction_code . "'
					WHERE id=" . intval($this->getId());
			Db::query($sql);
		}
		//
		return $this->vendor_transaction_code;
	}

