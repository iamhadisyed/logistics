	/**
	 * Shipping cost is not stored until customer makes an order.
	 * This will return the default shipping cost if any of the items
	 * in the basket are products
	 *
	 * @param boolean $formatted
	 */
	public function getShippingCost($formatted = false)
	{
		$cost = 0;
		// charge default passed if there are any products in the database.
		foreach ($this->getParcelGroups() as $parcelGroup)
		{
			if ($parcelGroup->getProductId() > 0)
			{
				$cost = CONFIG_SHIPPING_COST;
				break;
			}
		}
		//
		return ($formatted ? util_money($cost) : $cost);
	}



