	/**
	 * getAnyBasket. Returns the object array of Baskets.
	 * @param string $where
	 * @param string $activeOnly
	 * @param string $orderBy
	 * @return string
	 */
	public static function getAnyBasket($where = "", $activeOnly = true, $orderBy = "id")
	{
		$basket = new Basket();
		$ret = array();
		$ids = $basket->getAnyBasketIds($where, $activeOnly, $orderBy);

		if (count($ids)>0)
		{
			foreach ($ids as $i)
			{
				$ret[] = new Basket($i);
			}
			return $ret;
		}
		else return $ret;
	}

	/**
	 * getAnyBasketIds. Returns the object array of Basket ids.
	 * @param string $where
	 * @param string $activeOnly
	 * @param string $orderBy
	 * @return string
	 */
	public function getAnyBasketIds($where = "", $activeOnly = true, $orderBy = "id")
	{
		$ret	 = array();
		$whereSql = "WHERE deletedq <> 'Y' ";

		if ($where)	 $whereSql .= " AND $where";
		if ($activeOnly) $whereSql .= " AND active=1";
		 $sql = "SELECT {$this->pkey}
				 FROM {$this->tablename}
						 $whereSql
			 ORDER BY $orderBy";

		//echo "<p>$sql</p>";

		$result = Db::query($sql);
		while (list($pId) = mysqli_fetch_row($result))
		{
			$ret[] = $pId;
		}

		return $ret;
	}



