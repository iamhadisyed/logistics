	/**
	 * getBasketByOrderId. get the basket by order id
	 * @return array
	 */
	public function getBasketByOrderId()
	{
		// only pick up baskets that are orders
		if ($this->getOrderId() == 0) return;

		// get basket items
		$where = " order_id = " . $this->getOrderId();
		$basket = $this->getAnyBasketIds($where);

		// if no basket found, exit
		if (!isset($basket[0])) return;

		return $basket[0];

	}

	/**
	 * updateRow. update a basket row
	 * @return string
	 */
	public function updateRow($id, $quantity)
	{
		$BdetObj = new Basketitem($id);

		if ($quantity > 0)
		{
			$BdetObj->updateQuantity($quantity);
		}
		else
		{
			$BdetObj->delete();
		}
	}

	/**
	 * hasPackaging. does this basket have packaging
	 * @return boolean
	 */
	public function hasPackaging()
	{
		$basket_items = $this->getBasketItems();

		foreach ($basket_items as $basket_item)
		{
			if ($basket_item->getParcelGroup()->getProductId() != 0)
			{
				return true;
			}
		}

		return false;
	}

	/**
	 * Has packages - does this basket contain any parcel groups
	 * @return boolean
	 */
	public function hasParcelGroups()
	{
		$basket_items = $this->getBasketItems();
		foreach ($basket_items as $basket_item)
		{
			if ($basket_item->getParcelGroup()->getProductId() == 0)
			{
				return true;
			}
		}
		return false;
	}

